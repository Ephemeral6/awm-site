import heapq, sys
sys.set_int_max_str_digits(0)
exec(open('work/gen_cert.py').read().split("def key(st)")[0])   # reuse walk/valid/hit/step/COST
B = 19
s0 = (0, 0, 25, 37, 1)
dist = {s0: 0}; pq = [(0, s0)]
while pq:
    d, st = heapq.heappop(pq)
    if d > dist[st]: continue
    for a in range(6):
        n = step(st, a)
        if n == 'WIN':
            assert d + COST[a] > B; continue
        nd = d + COST[a]
        if nd <= B and nd < dist.get(n, 99):
            dist[n] = nd; heapq.heappush(pq, (nd, n))
print('entries', len(dist))
by = {}
for (sm, o, y, x, f), d in dist.items():
    by.setdefault(x, []).append('(⟨%s, %s, %d, %d, %d⟩, %d)' % ('true' if sm else 'false', 'true' if o else 'false', y, x, f, d))
L = ['import Game.L4Macro', 'namespace L4M', '', '/-- Certificate (generated by work/gen_lean_cert.py): every state reachable from `s0` with cost ≤ 19,',
     '    bucketed by column, with its least cost.  Lean re-checks it in `L4MacroProof.lean`. -/',
     'def bucket : Nat → List (MSt × Nat)']
for x in sorted(by):
    L.append('  | %d => [%s]' % (x, ', '.join(by[x])))
L.append('  | _ => []')
L.append('')
L.append('def cols : List Nat := [%s]' % ', '.join(map(str, sorted(by))))
L.append('end L4M')
open('lean/Game/L4MacroCert.lean', 'w', encoding='utf-8').write('\n'.join(L) + '\n')
