# generator used for lean/L4RowNN.lean (see inline script in transcript; reproduced here)
for t in range(40):
    ls=["import L4CheckDefs","/-! kernel check of row t = %d of model M4 (generated by work/gen_rows.py) -/"%t,"namespace L4"]
    for l in range(64):
        ls.append("theorem ctl_%d_%d : checkTL %d %d = true := by decide +kernel"%(t,l,t,l))
    pf="lt_zero_all"
    for l in range(64): pf="(lt_succ_all %s ctl_%d_%d)"%(pf,t,l)
