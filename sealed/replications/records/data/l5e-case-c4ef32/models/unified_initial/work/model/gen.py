"""Generate Lean data for the strict L5 model: wall bitmasks and the certificate table T.
T[key] = 0 if state not in the reachable set R, else min(H,62)+1.  H = backward potential."""
import heapq, json
import fast
from l5map import BARRIER, SWITCH, base_walkable, inrect
from rules import initial
fast.GROW_WALLCHECK = True
QUADS=[(0,0),(0,2),(2,0),(2,2)]
ACTS=[('move',d) for d in 'UDLR']+[('shrink',q) for q in QUADS]+[('grow',q) for q in QUADS]+[('shot',None),('tele',None)]
FI={'U':0,'D':1,'L':2,'R':3}
def key(t):
    r,c,s,f,oc,od,ep=t
    assert r%2==1 and c%2==1 and 0<=r<64 and 0<=c<64
    return (((((r//2)*32 + c//2)*2 + (1 if s==4 else 0))*4 + FI[f])*8 + 4*oc + 2*od + ep)
s0=fast.totuple(initial())
R={s0}; order=[s0]; edges={}
i=0
while i<len(order):
    t=order[i]; i+=1; out=[]
    for a in ACTS:
        n,cost,cr,win=fast.step(t,a,'full')
        out.append((n,cost,win))
        if not win and n not in R: R.add(n); order.append(n)
    edges[t]=out
print('reachable',len(R))
INF=10**9; H={t:INF for t in order}; rev={t:[] for t in order}
for t,out in edges.items():
    for n,cost,win in out:
        if win: H[t]=min(H[t],10 if t[6] else 0)
        else: rev[n].append((t,cost))
pq=[(v,t) for t,v in H.items() if v<INF]; heapq.heapify(pq)
while pq:
    v,t=heapq.heappop(pq)
    if v>H[t]: continue
    for p,c in rev[t]:
        if v+c<H[p]: H[p]=v+c; heapq.heappush(pq,(H[p],p))
print('H(start)',H[s0])
T=0
for t in order:
    T |= (min(H[t],62)+1) << (6*key(t))
def mask(pred):
    m=0
    for r in range(64):
        for c in range(64):
            if pred(r,c): m |= 1 << (r*64+c)
    return m
W0=mask(base_walkable)
WC=mask(lambda r,c: inrect(r,c,BARRIER['c'])); WD=mask(lambda r,c: inrect(r,c,BARRIER['d']))
json.dump(dict(reachable=len(R),H0=H[s0],maxkey=max(key(t) for t in order)),open('gen_result.json','w'))
with open('../../lean/L5Data.lean','w',encoding='utf-8') as f:
    f.write('/-! Generated by work/model/gen.py from the initial L5 frame (map) and the search (certificate).\n'
            '    Map masks are level data; `cert` is an untrusted table that `L5Proof` re-checks against `L5Model.step`. -/\n')
    f.write('namespace L5\n')
    f.write('/-- base walkable cells (bit r*64+c): floor 2, b, e-pad, f-pad, goal box, block start. -/\n')
    f.write('def W0 : Nat := 0x%x\n' % W0)
    f.write('/-- c-barrier cells (rows 33-36, cols 29-31). -/\ndef WC : Nat := 0x%x\n' % WC)
    f.write('/-- d-barrier cells (rows 11-13, cols 33-36). -/\ndef WD : Nat := 0x%x\n' % WD)
    f.write('/-- certificate, split by block-row index: the entry for key k sits in `certRow (k / 2048)`\n'
            '    at bit 6*(k % 2048); 0 = not in the certified set, v = min(H,62)+1. -/\n')
    f.write('def certRow : Nat → Nat\n')
    for i in range(32):
        v = (T >> (6*2048*i)) & ((1 << (6*2048)) - 1)
        f.write('  | %d => 0x%x\n' % (i, v))
    f.write('  | _ => 0\n')
    f.write('end L5\n')
print('T bits', T.bit_length())
